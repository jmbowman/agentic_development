import sys
from pathlib import Path

source, out = Path(sys.argv[1]), Path(sys.argv[2])
rows = source.read_text().splitlines()[1:]
(out / "expected.csv").write_text("\n".join(dict.fromkeys(rows)) + "\n")
EOF
