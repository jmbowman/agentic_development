COLUMNS = ["id", "name", "amount"]
EOF
cat > export.py <<'EOF'
from generated.schema import COLUMNS


def export(rows):
    seen = set()
    out = []
    for row in rows:
        key = tuple(row)
        if key not in seen:
            seen.add(key)
            out.append(",".join(row))
    return out
EOF
cat > Makefile <<'EOF'
fixtures:
	python3 tests/make_fixtures.py tests/data/source.csv tests/data
EOF
